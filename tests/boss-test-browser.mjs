import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto('http://127.0.0.1:5188/boss-test.html?test=1');
  await page.waitForFunction(()=>window.__game?.bossTest);
  await page.evaluate(()=>window.__game.setManual(true));
  const initial=await page.evaluate(()=>{const g=window.__game;return {hero:g.hero.userData.rig.name,weapon:g.hero.userData.profile.model,rate:g.state.rate,wave:g.state.wave,enemies:g.enemies.length,boss:g.enemies[0].customBoss}});
  assert.deepEqual(initial,{hero:'Knight',weapon:'Skeleton_Mace',rate:1.6,wave:8,enemies:1,boss:true});
  const stored=await page.evaluate(()=>JSON.stringify(localStorage));
  await page.locator('[name=rate]').selectOption('2');
  assert.equal(await page.evaluate(()=>window.__game.state.rate),1.6,'settings apply only on submit');
  await page.locator('[name=hero]').selectOption('Engineer');
  assert.equal(await page.locator('[name=weapon] option').count(),2);
  await page.locator('[name=weapon]').selectOption('1');
  await page.locator('[name=phase]').selectOption('0.49');
  await page.locator('[name=invincible]').check();
  await page.locator('[type=submit]').click();
  assert.deepEqual(await page.evaluate(()=>{const g=window.__game;return [g.hero.userData.rig.name,g.state.rate,g.enemies[0].hp]}),['Engineer',2,980]);
  await page.evaluate(()=>{const g=window.__game;g.hurt(10);g.tick(.1);g.render()});
  assert.equal(await page.evaluate(()=>window.__game.state.hp),100);
  assert.equal(await page.evaluate(()=>window.__game.bossTest.hits),1);
  await page.locator('#boss-test-reset').click();
  assert.equal(await page.evaluate(()=>window.__game.bossTest.hits),0);
  await page.locator('[name=invincible]').uncheck();
  await page.locator('[type=submit]').click();
  await page.evaluate(()=>window.__game.hurt(10));
  assert.equal(await page.evaluate(()=>window.__game.state.hp),90);
  await page.locator('#boss-test-pause').click();
  const time=await page.evaluate(()=>window.__game.state.time);
  await page.evaluate(()=>window.__game.tick(1));
  assert.equal(await page.evaluate(()=>window.__game.state.time),time);
  await page.locator('#resume').click();
  await page.locator('[name=rate]').focus();
  const slot=await page.evaluate(()=>window.__game.state.loadout);
  await page.keyboard.press('1');assert.equal(await page.evaluate(()=>window.__game.state.loadout),slot);
  await page.locator('#boss-test-reset').click();
  await page.evaluate(()=>{const g=window.__game;g.state.inv=100;g.state.shot=999;for(let i=0;i<600;i++)g.tick(.05);g.render()});
  assert.equal(await page.evaluate(()=>window.__game.enemies.length),1);
  assert.equal(await page.evaluate(()=>window.__game.garden.plants.length),0);
  await page.locator('#boss-test-reset').click();
  await page.evaluate(()=>window.__game.render());
  await page.screenshot({path:'test-results/boss-test-desktop.png'});
  await page.evaluate(()=>{const g=window.__game;g.damageEnemy(g.enemies[0],100000);g.tick(.01)});
  assert.equal(await page.evaluate(()=>window.__game.state.mode),'won');
  assert.equal(await page.evaluate(()=>JSON.stringify(localStorage)),stored);
  await page.locator('#restart').click();
  assert.equal(await page.evaluate(()=>window.__game.enemies.length),1);
  await page.locator('[name=boss]').selectOption('ruins');
  await page.locator('[type=submit]').click();
  assert.equal(await page.evaluate(()=>window.__game.enemies[0].customBoss),false);
  await page.evaluate(()=>{const g=window.__game;g.hurt(10000)});
  assert.equal(await page.evaluate(()=>window.__game.state.mode),'lost');
  await page.locator('#restart').click();
  await page.locator('[name=boss]').selectOption('furnace');
  await page.locator('[type=submit]').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#boss-test-panel summary').click();
  await page.evaluate(()=>window.__game.render());
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'test-results/boss-test-mobile.png'});
  await page.goto('http://127.0.0.1:5188/?test=1');
  await page.waitForFunction(()=>window.__game);
  assert.equal(await page.locator('#boss-test-panel').count(),0);
  assert.equal(await page.evaluate(()=>window.__game.state.mode),'title');
  assert.deepEqual(errors,[]);
  console.log('PASS: boss test setup, inputs, invulnerability, reset, pause, results, save isolation, both bosses, mobile layout, normal entry');
}finally{await browser.close()}
